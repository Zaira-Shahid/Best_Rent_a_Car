export function getCarsBySlugs(slugs: string[]): CarModel[] {
  return slugs
    .map((slug) => carModels.find((car) => car.slug === slug))
    .filter((car): car is CarModel => Boolean(car));
}

export function getCarsForCategory(slug: string): CarModel[] {
  const section = fleetSections.find((item) => item.slug === slug);
  if (section) return getCarsBySlugs(section.carSlugs);
  return carModels.filter((car) => car.category === slug);
}

